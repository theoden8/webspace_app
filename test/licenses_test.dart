import 'dart:io';

import 'package:flutter/foundation.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:webspace/services/licenses.dart';

/// The data files the app ships carry their licences into the app's licence
/// page, read from the bundled text.
void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  setUp(() {
    LicenseRegistry.reset();
    registerLicenses();
  });
  tearDown(LicenseRegistry.reset);

  // The first entries are the bundled files; the Rust crates' come last and
  // need the native library, so each search stops before them.
  Future<String> licenceOf(String package) async {
    final entry = await LicenseRegistry.licenses
        .firstWhere((e) => e.packages.contains(package));
    return entry.paragraphs.map((p) => p.text).join('\n');
  }

  for (final (package, licence, id) in [
    ('ClearURLs (rules data)', 'GNU Lesser General Public License v3.0', 'CURL-011'),
    ('Hagezi DNS Blocklists (domain data)', 'GNU General Public License v3.0', 'DNS-009'),
    ('EasyList filter lists (filter data)', 'CC BY-SA 3.0', 'CB-007'),
  ]) {
    test('$package is listed under its licence ($id)', () async {
      expect(await licenceOf(package), contains(licence));
    });
  }

  test('EasyList is credited to its authors (CB-007)', () async {
    expect(await licenceOf('EasyList filter lists (filter data)'),
        contains('The EasyList authors'));
  });

  // Every text under assets/licenses is a component that neither pub's nor
  // Cargo's collector reaches, so one left unregistered never shows.
  test('every licence text the app bundles is on the licences page (LICENSE-003)', () async {
    String lines(Iterable<String> all) =>
        all.map((l) => l.trimLeft()).where((l) => l.isNotEmpty).join('\n');
    final wanted = {
      for (final f in Directory('assets/licenses').listSync().whereType<File>())
        if (f.path.endsWith('.txt')) f.path: lines(f.readAsLinesSync()),
    };
    expect(wanted, isNotEmpty);
    await for (final entry in LicenseRegistry.licenses) {
      final text = lines(entry.paragraphs.map((p) => p.text));
      wanted.removeWhere((_, file) => file == text);
      if (wanted.isEmpty) break;
    }
    expect(wanted.keys, isEmpty, reason: 'registered in lib/services/licenses.dart');
  });

  test("each pod is one entry, as CocoaPods' acknowledgements list them (LICENSE-003)", () {
    const markdown = '# Acknowledgements\n'
        'This application makes use of the following third party libraries:\n\n'
        '## SDWebImage\n\nCopyright (c) 2009-2020 Olivier Poitrey\n\nPermission is hereby granted\n\n'
        '## Tor\n\nCopyright (c) 2015-2026 The iCepa Contributors\n'
        'Generated by CocoaPods - https://cocoapods.org\n';
    expect(podNotices(markdown), [
      ('SDWebImage', 'Copyright (c) 2009-2020 Olivier Poitrey\n\nPermission is hereby granted'),
      ('Tor', 'Copyright (c) 2015-2026 The iCepa Contributors'),
    ]);
    expect(podNotices('# Acknowledgements\nno pods\n'), isEmpty);
  });

  test('each Maven artifact is one entry with its POM licences (LICENSE-003)', () {
    const json = '[{"group":"com.google.guava","artifact":"guava","version":"33.5.0-android",'
        '"licences":[{"name":"Apache License, Version 2.0","url":"http://www.apache.org/licenses/LICENSE-2.0.txt"}]},'
        '{"group":"x","artifact":"bad","version":1,"licences":[]}]';
    expect(mavenNotices(json), [
      (
        'com.google.guava:guava',
        'Version: 33.5.0-android\nLicense: Apache License, Version 2.0 (http://www.apache.org/licenses/LICENSE-2.0.txt)',
      ),
    ]);
  });

  test('the redirect scripts the adblock build takes in are listed apart from its crates (LICENSE-003)', () {
    const licence = 'Copyright (c) 2021-2023 Duck Duck Go, Inc.\n\n'
        'This work as a whole is licensed under the Apache License, Version 2.0';
    final (package, text) = adblockNotice({
      'kind': 'redirect-resources',
      'name': 'DuckDuckGo tracker-surrogates',
      'version': '1cca57fa1edc945f208423d478c1d2aa50655141',
      'license': 'Apache-2.0 AND MPL-2.0',
      'repository': 'https://github.com/duckduckgo/tracker-surrogates',
      'description': 'Scripts that stand in for the APIs of trackers and ad libraries.',
      'authors': <Object>[],
      'license_files': [
        {'name': 'LICENSE.md', 'text': licence},
      ],
      'license_texts': <Object>[],
    })!;
    expect(package, 'DuckDuckGo tracker-surrogates (redirect scripts the content blocker serves)');
    expect(text, contains('License: Apache-2.0 AND MPL-2.0'));
    expect(text, contains('Source: https://github.com/duckduckgo/tracker-surrogates'));
    expect(text, contains('--- LICENSE.md ---\n\n$licence'));
    expect(adblockNotice({'kind': 'crate', 'name': 'adblock', 'license': 'MPL-2.0'})?.$1,
        'adblock (Rust crate, transitive via adblock-rust)');
    expect(adblockNotice({'kind': 'crate', 'name': ''}), isNull);
  });

  test('the README names EasyList and adblock-rust (CB-007)', () {
    final readme = File('README.md').readAsStringSync();
    expect(readme, contains('EasyList'));
    expect(readme, contains('adblock-rust'));
  });
}
